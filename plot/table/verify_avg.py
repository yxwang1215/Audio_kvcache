def calculate_avg(values):
    """计算平均值"""
    return sum(values) / len(values)

# 主程序
if __name__ == '__main__':
    print("验证 Avg. 列的计算：\n")
    print("=" * 100)
    print(f"{'方法':<15} | {'计算值':>10} | {'表格值':>10} | {'差值':>10} | {'状态':>6}")
    print("=" * 100)
    
    errors = []
    model_num = 0
    prev_method = None
    
    for i, row in enumerate(rows_data):
        method = row['method']
        values = row['values']
        avg_table = row['avg']
        
        # 检测新模型
        if method == 'Full KV' and prev_method != 'Full KV' and prev_method is not None:
            model_num += 1
            print()
        
        calculated_avg = calculate_avg(values)
        diff = abs(calculated_avg - avg_table)
        
        status = "✓" if diff < 0.05 else "✗"
        
        print(f"{method:<15} | {calculated_avg:10.2f} | {avg_table:10.2f} | {diff:10.3f} | {status:>6}")
        
        if diff >= 0.05:
            errors.append({
                'method': method,
                'calculated': calculated_avg,
                'table': avg_table,
                'diff': diff
            })
        
        prev_method = method
    
    print("=" * 100)
    
    if errors:
        print(f"\n发现 {len(errors)} 个错误：\n")
        for err in errors:
            print(f"  {err['method']:15s}: 计算值={err['calculated']:8.2f}, 表格值={err['table']:8.2f}, 差值={err['diff']:.3f}")
    else:
        print("\n✓ 所有 Avg. 值计算正确！")
